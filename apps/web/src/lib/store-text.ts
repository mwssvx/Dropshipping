const TEXTS: Record<string, StoreText> = { de, fr, es, it, nl };

/** The store's fixed words in a language; English when there's no language or we don't have it. */
export function storeText(language: string | null | undefined): StoreText {
  return (language && TEXTS[language]) || en;
}

/** Country names in the buyer's language, for the checkout's country list. */
export function countryNames(language: string | null | undefined) {
  const names = new Intl.DisplayNames([language || "en"], { type: "region" });
  return (code: string, fallback: string) => {
    try {
      return names.of(code) ?? fallback;
    } catch {
      return fallback;
    }
  };
}
